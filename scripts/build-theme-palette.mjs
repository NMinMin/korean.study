import fs from 'node:fs';
import postcss from 'postcss';

// Convert fixed stylesheet colors to role-specific tokens. The fallback keeps
// the light theme identical; dark tokens retain tinted feedback and accents.
const tokens = new Map();
if (fs.existsSync('src/styles/theme-palette.css')) {
  postcss.parse(fs.readFileSync('src/styles/theme-palette.css', 'utf8')).walkDecls(d => tokens.set(d.prop, d.value));
}
function token(hex, role) {
  let raw = hex.slice(1).toLowerCase();
  if (raw.length === 3) raw = [...raw].map(c => c + c).join('');
  if (raw.length !== 6) return hex;
  const rgb = [0, 2, 4].map(i => parseInt(raw.slice(i, i + 2), 16));
  const [lo, hi] = [Math.min(...rgb), Math.max(...rgb)];
  const light = (hi + lo) / 2;
  let result;
  if (role === 'surface' && light > 170) {
    const chroma = hi - lo;
    result = chroma < 8 ? [33, 30, 47] : rgb.map((v, i) => Math.round([26, 23, 39][i] + (v - lo) * .4));
  } else if (role === 'border' && light > 120) {
    result = rgb.map((v, i) => Math.round([57, 52, 71][i] + (v - lo) * .3));
  } else if (role === 'text' && light < 205) {
    if (hi - lo < 65) result = light < 110 ? [237, 232, 255] : [190, 182, 210];
    else result = rgb.map(v => Math.round(v + (255 - v) * .42));
  } else return hex;
  const name = `--ks-${role}-${raw}`;
  tokens.set(name, '#' + result.map(v => v.toString(16).padStart(2, '0')).join(''));
  return `var(${name}, ${hex})`;
}
for (const file of ['src/styles/dashboard.css', 'src/pages/admin.css']) {
  const root = postcss.parse(fs.readFileSync(file, 'utf8'));
  root.walkDecls(decl => {
    const role = /^(background|background-color|background-image)$/.test(decl.prop) ? 'surface'
      : /^(color|fill|stroke|-webkit-text-fill-color)$/.test(decl.prop) ? 'text'
        : /^border($|-)/.test(decl.prop) ? 'border' : null;
    if (!role) return;
    // Tokenized declarations are left untouched on subsequent runs.
    if (decl.value.includes('--ks-')) {
      for (const match of decl.value.matchAll(/var\(--ks-(surface|text|border)-[a-f0-9]+,\s*(#[a-f0-9]+)/gi)) token(match[2], match[1]);
      return;
    }
    decl.value = decl.value.replace(/#[a-f0-9]{3,8}\b/gi, hex => token(hex, role));
    decl.value = decl.value.replace(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)(?:\s*,\s*([\d.]+))?\s*\)/gi, (original, r, g, b, alpha = '1') => {
      const hex = '#' + [r, g, b].map(v => Number(v).toString(16).padStart(2, '0')).join('');
      const converted = token(hex, role);
      if (converted === hex) return original;
      const name = converted.match(/var\(([^,]+)/)[1];
      const dark = tokens.get(name);
      const channels = [1, 3, 5].map(i => parseInt(dark.slice(i, i + 2), 16));
      const alphaName = `${name}-a${alpha.replace('.', '_')}`;
      tokens.set(alphaName, `rgba(${channels.join(', ')}, ${alpha})`);
      return `var(${alphaName}, ${original})`;
    });
  });
  fs.writeFileSync(file, root.toString());
}
fs.writeFileSync('src/styles/theme-palette.css', '/* Generated by scripts/build-theme-palette.mjs. Light colors remain in CSS fallbacks. */\n:root[data-theme="dark"] {\n' + [...tokens].sort(([a], [b]) => a.localeCompare(b)).map(([name, value]) => `  ${name}: ${value};`).join('\n') + '\n}\n');
console.log(`Generated ${tokens.size} dark palette tokens.`);
